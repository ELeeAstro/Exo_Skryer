"""Write one transit_1d retrieval config per limb angle: theta<NNN>/retrieval_config.yaml.

Reproduces the per-angle POSEIDON free retrievals of Alderson et al. (2026, arXiv:2610.18806, Sec. 4.5):
each limb angle is retrieved as its own 1D planet.

  POSEIDON (paper)                        Exo Skryer (here)
  isothermal T                            vert_Tp: isothermal, T_iso
  free log X: CH4 CO CO2 H2O H2S K Na     vert_chem: constant_vmr, log_10_f_<sp>
    SO2 H- (H2/He fill, He/H2 = 0.17)
  R_p_ref at 10 bar                       R_p at log_10_p_ref = 1
  1e-8 - 100 bar, 100 layers              p_top 1e-8, p_bot 100, nlay 100
  deck_haze: opaque deck below          opac_cloud: deck_haze (exact analogue of POSEIDON's model):
    log_P_cloud, haze n a sigma0            log_10_p_deck, log_10_a_haze, gamma_haze
    (lambda/0.35um)^gamma
  R = 30,000 opacity sampling             os R30000 tables
  PyMultiNest, 2000 live points           pymultinest, n_live_points 2000

Gravity is not free in the paper: POSEIDON fixes the planet mass, so g = G M_p / R_p_ref^2 follows the
free reference radius. Here M_p is fixed (no log_10_g), which does the same (build_common.resolve_gravity).
M_p = 0.5 MJ is the paper's rounded value: check against the POSEIDON set-up of Lewis et al. (in prep).
The paper gives no prior ranges ("wide, uniform");
POSEIDON's defaults (core.set_priors) are used: R_p_ref 0.85-1.15 R_p, T 400-3000 K, log X -12..-1,
log_a -4..8, gamma -20..2, log_P_cloud -6..2.

    python make_configs.py              # all angles in obs/
    python make_configs.py --angles 0 180
"""
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = "../../.."                     # from theta<NNN>/ back to the repo root
OS = f"{ROOT}/opac_data/os"
CIA = f"{ROOT}/opac_data/cia"

SPECIES = ("CH4", "CO", "CO2", "H2O", "H2S", "K", "Na", "SO2")

TEMPLATE = """# WASP-17b limb angle theta = {theta} deg (0 = morning/west, 180 = evening/east).
# Generated by ../make_configs.py: edit that script, not this file.
# Per-angle 1D free retrieval reproducing Alderson et al. (2026) Sec. 4.5 (POSEIDON); see make_configs.py.

data:
  obs: ../obs/W17b_limb_theta{theta:03d}.txt
  obs_east: None
  obs_west: None
  stellar: None

physics:
  nlay: 100
  vert_Tp: isothermal
  vert_alt: p_ref
  vert_chem: constant_vmr
  vert_mu: dynamic
  vert_cloud: None
  opac_line: os
  opac_ray: os
  opac_cia: os
  opac_cloud: deck_haze         # POSEIDON deck_haze: opaque deck + haze
  opac_special: on              # H- bound-free
  rt_scheme: transit_1d
  contri_func: False
  refraction: None

opac:
  wl_master: {OS}/wl_R30000.txt
  full_grid: False
  ck: False
  line:
{line}
  ray:
    - {{species: H2}}
    - {{species: He}}
  cia:
    - {{species: H2-H2, path: {CIA}/H2-H2_2011.zarr.zip}}
    - {{species: H2-He, path: {CIA}/H2-He_2011.zarr.zip}}
  special:
    - {{species: H-, bf: True, ff: False}}
  cloud: None

params:
  - {{ name: R_s,          dist: delta, value: 1.583, transform: identity, init: 1.583 }}  # stellar radius [R_sun]
  - {{ name: p_bot,        dist: delta, value: 100.0, transform: identity, init: 100.0 }}  # [bar]
  - {{ name: p_top,        dist: delta, value: 1e-8,  transform: identity, init: 1e-8 }}   # [bar]
  - {{ name: log_10_p_ref, dist: delta, value: 1.0,   transform: identity, init: 1.0 }}    # 10 bar, as POSEIDON
  - {{ name: M_p,          dist: delta, value: 0.5,   transform: identity, init: 0.5 }}    # [M_jup]; g = G M_p / R_p^2 at p_ref
  - {{ name: R_p,    dist: uniform, low: 1.615, high: 2.185,  transform: logit, init: 1.7 }}    # 0.85-1.15 x 1.9 R_jup, at p_ref
  - {{ name: T_iso,  dist: uniform, low: 400.0, high: 3000.0, transform: logit, init: 1200.0 }} # [K]
{abund}
  # POSEIDON deck_haze: deck opaque at P_lay > 10**log_10_p_deck [bar];
  # haze kappa = n 10**log_10_a_haze sigma_0 (lambda / 0.35 um)**gamma_haze
  - {{ name: log_10_p_deck, dist: uniform, low: -6.0,  high: 2.0, transform: logit, init: -2.0 }}
  - {{ name: log_10_a_haze, dist: uniform, low: -4.0,  high: 8.0, transform: logit, init: 0.0 }}
  - {{ name: gamma_haze,    dist: uniform, low: -20.0, high: 2.0, transform: logit, init: -4.0 }}

sampling:
  engine: pymultinest
  pymultinest:
    n_live_points: 2000
    evidence_tolerance: 0.5
    sampling_efficiency: 0.3
    n_iter_before_update: 100
    null_log_evidence: -1.0e99
    max_modes: 100
    mode_tolerance: -1.0e99
    seed: -1
    verbose: true
    outputfiles_basename: pymultinest_
    resume: false
    importance_nested_sampling: false
    multimodal: false
    const_efficiency_mode: false
  nautilus:                      # alternative: set engine: nautilus
    n_live: 2000
    f_live: 0.01
    n_eff: 10000
    equal_weight: true
    verbose: true
    seed: 42

runtime:
  platform: cpu
  threads: 8
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--angles", type=int, nargs="*", help="limb angles [deg] (default: every obs/ file)")
    args = ap.parse_args()
    angles = args.angles or sorted(int(p.stem[-3:]) for p in (HERE / "obs").glob("W17b_limb_theta*.txt"))
    line = "\n".join(f"    - {{species: {s}, path: {OS}/{s}_R30000.zarr.zip}}" for s in SPECIES)
    abund = "\n".join(f"  - {{ name: log_10_f_{s:<4s}, dist: uniform, low: -12.0, high: -1.0, transform: logit, init: -6.0 }}"
                      for s in SPECIES + ("H-",))
    for theta in angles:
        if not (HERE / "obs" / f"W17b_limb_theta{theta:03d}.txt").exists():
            raise SystemExit(f"no obs/W17b_limb_theta{theta:03d}.txt: run prepare_obs.py first")
        d = HERE / f"theta{theta:03d}"
        d.mkdir(exist_ok=True)
        (d / "retrieval_config.yaml").write_text(TEMPLATE.format(
            theta=theta, OS=OS, CIA=CIA, line=line, abund=abund))
        print(f"wrote {d.name}/retrieval_config.yaml")


if __name__ == "__main__":
    main()
